
<?php

session_start();

require_once "../config/database.php";


/*
|--------------------------------------------------------------------------
| حماية الصفحة
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION["user_id"])) {

    header("Location: ../login.php");
    exit;

}


/*
|--------------------------------------------------------------------------
| الحصول على رقم العقار
|--------------------------------------------------------------------------
*/

$id = filter_input(
    INPUT_GET,
    "id",
    FILTER_VALIDATE_INT
);

if (!$id) {

    header("Location: properties.php");
    exit;

}


try {

    /*
    |--------------------------------------------------------------------------
    | الحصول على صورة العقار قبل الحذف
    |--------------------------------------------------------------------------
    */

    $stmt = $conn->prepare("
        SELECT main_image
        FROM properties
        WHERE id = ?
        LIMIT 1
    ");

    $stmt->execute([$id]);

    $property = $stmt->fetch(PDO::FETCH_ASSOC);


    /*
    |--------------------------------------------------------------------------
    | التأكد من وجود العقار
    |--------------------------------------------------------------------------
    */

    if (!$property) {

        header("Location: properties.php");
        exit;

    }


    /*
    |--------------------------------------------------------------------------
    | حذف العقار
    |--------------------------------------------------------------------------
    */

    $stmt = $conn->prepare("
        DELETE FROM properties
        WHERE id = ?
    ");

    $stmt->execute([$id]);


    /*
    |--------------------------------------------------------------------------
    | حذف الصورة من مجلد الصور
    |--------------------------------------------------------------------------
    */

    if (!empty($property["main_image"])) {

        $imagePath =
            "../assets/images/properties/"
            . $property["main_image"];


        if (file_exists($imagePath)) {

            unlink($imagePath);

        }

    }


    /*
    |--------------------------------------------------------------------------
    | العودة إلى قائمة العقارات
    |--------------------------------------------------------------------------
    */

    header(
        "Location: properties.php?deleted=1"
    );

    exit;


} catch (PDOException $e) {

    die(
        "حدث خطأ أثناء حذف العقار."
    );

}